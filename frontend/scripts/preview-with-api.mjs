// Deploys a Vercel PREVIEW of the site whose /api is THIS BRANCH'S backend, so a change that needs a new endpoint (the hiring desk's /api/jobs/board) can be checked on the
// deployed page before anything reaches production.
//
//   node scripts/preview-with-api.mjs            deploy a preview and print its address
//   node scripts/preview-with-api.mjs --prepare-only    build the folder that would be deployed, print where it is, deploy nothing
//
// How: the site is static, and its API address (VITE_API_BASE) is set on the Vercel project for Production AND Preview, pointing at the live API. Here the build is given an
// empty VITE_API_BASE (`--build-env`), so the page asks its own address for /api/..., and the backend (backend/src, with the data files it carries) goes into the same deployment as
// serverless functions. Same origin: the preview's sign-in covers the API too, there is nothing to allow in CORS, and the production API is never asked. The community (accounts, the
// feed) is closed on this API (NETWORK_ENABLED=0): a function has no disk that lasts. It is the same Express app the server runs, over the data files in the commit.
//
// It only ever makes a preview: `--prod` is refused. Run it from a clean checkout of the commit to be shown (a working copy's uncommitted data files would go with it).
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const here = path.dirname(fileURLToPath(import.meta.url));
const frontend = path.resolve(here, '..');
const backend = path.resolve(frontend, '..', 'backend');
const args = process.argv.slice(2);

if (args.includes('--prod') || args.includes('--production')) {
  console.error('This script only makes previews. A production deploy is `vercel deploy --prod --cwd frontend`, run by the owner after review.');
  process.exit(2);
}
const prepareOnly = args.includes('--prepare-only');

const out = mkdtempSync(path.join(tmpdir(), 'still-early-preview-'));
const skip = /[\\/](node_modules|dist|\.vercel)([\\/]|$)/;
cpSync(frontend, out, { recursive: true, filter: (src) => !skip.test(src) });

// The project link (which Vercel project this preview belongs to), copied, never changed.
const link = path.join(frontend, '.vercel', 'project.json');
if (existsSync(link)) { mkdirSync(path.join(out, '.vercel'), { recursive: true }); cpSync(link, path.join(out, '.vercel', 'project.json')); }

// The backend, beside the functions that serve it. Its own package.json says "type": "module" so its .js files are read as modules.
const be = path.join(out, 'api', '_be');
cpSync(path.join(backend, 'src'), path.join(be, 'src'), { recursive: true });
writeFileSync(path.join(be, 'package.json'), `${JSON.stringify({ type: 'module' }, null, 2)}\n`);
writeFileSync(path.join(out, 'api', '_app.mjs'), [
  '// Generated by frontend/scripts/preview-with-api.mjs: the backend of this branch, as the preview\'s own /api.',
  "import { createApp } from './_be/src/app.js';",
  'export default createApp();',
  '',
].join('\n'));
// In this project Vercel matched a catch-all file name (`[...path]`, as .mjs or .js) against ONE path segment only (/api/health answered, /api/jobs/board was a platform 404), and a
// rewrite to a function was not applied either. What works is a file per depth, with dynamic folders: api/[s1]/index.js answers /api/x, api/[s1]/[s2]/index.js answers /api/x/y,
// and so on to the deepest address the API has (six segments). `x-served-by` says which depth answered.
const DEPTH = 6;
for (let d = 1; d <= DEPTH; d += 1) {
  const dir = path.join(out, 'api', ...Array.from({ length: d }, (_, i) => `[s${i + 1}]`));
  mkdirSync(dir, { recursive: true });
  writeFileSync(path.join(dir, 'index.js'), [
    `// Generated by frontend/scripts/preview-with-api.mjs (depth ${d}).`,
    `import app from '${'../'.repeat(d)}_app.mjs';`,
    `export default (req, res) => { res.setHeader('x-served-by', 'depth-${d}'); return app(req, res); };`,
    '',
  ].join('\n'));
}

// The backend's own dependencies join the site's for this deployment only (the committed package files are untouched).
const pkg = JSON.parse(readFileSync(path.join(out, 'package.json'), 'utf8'));
const beDeps = JSON.parse(readFileSync(path.join(backend, 'package.json'), 'utf8')).dependencies ?? {};
pkg.dependencies = { ...pkg.dependencies, ...beDeps };
writeFileSync(path.join(out, 'package.json'), `${JSON.stringify(pkg, null, 2)}\n`);

const config = JSON.parse(readFileSync(path.join(out, 'vercel.json'), 'utf8'));
config.installCommand = 'npm install --no-audit --no-fund'; // the committed lock file does not list the backend's packages
config.functions = { 'api/**/*.js': { includeFiles: 'api/_be/src/data/**', maxDuration: 30 } };
writeFileSync(path.join(out, 'vercel.json'), `${JSON.stringify(config, null, 2)}\n`);

console.log(`prepared ${out}`);
if (prepareOnly) process.exit(0);

const run = spawnSync('npx', ['vercel', 'deploy', '--cwd', out, '--build-env', 'VITE_API_BASE=', '--env', 'NETWORK_ENABLED=0'], { encoding: 'utf8', shell: process.platform === 'win32', maxBuffer: 1 << 26 });
process.stderr.write(run.stderr ?? '');
const urls = `${run.stdout ?? ''}`.match(/https:\/\/[a-z0-9-]+\.vercel\.app/g) ?? [];
if (run.status !== 0 || !urls.length) { console.error('The deploy did not finish.'); process.exit(run.status || 1); }
console.log(`preview: ${urls[0]}`);
console.log(`its API:  ${urls[0]}/api/jobs/board`);
// Tidy up the temporary folder; on Windows a file can still be held for a moment, which must not turn a good deploy into an error.
try { rmSync(out, { recursive: true, force: true, maxRetries: 5, retryDelay: 300 }); } catch (e) { console.log(`(left the temporary folder ${out}: ${e.code})`); }
